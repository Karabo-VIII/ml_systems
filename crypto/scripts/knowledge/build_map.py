def dead_list_head():
    """Highest D-number actually present in the dead-list register (the freshness-critical field)."""
    try:
        with open(DEAD_LIST, encoding="utf-8", errors="replace") as fh:
            nums = [int(m) for m in re.findall(r"\bD(\d{2,3})\b", fh.read())]
        return max(nums) if nums else 0
    except Exception:
        return 0


def render():
    return _TEMPLATE.replace("__DN__", "%02d" % dead_list_head())


def main(argv):
    body = render()
    if "--check" in argv:
        try:
            with open(MAP, encoding="utf-8", errors="replace") as fh:
                cur = fh.read()
        except Exception:
            cur = ""
        if cur.strip() != body.strip():
            sys.stderr.write("KNOWLEDGE_MAP.md is STALE vs the live dead-list head -- run "
                             "`python crypto/scripts/knowledge/build_map.py` and commit the result.\n")
            return 2
        return 0
    with open(MAP, "w", encoding="utf-8") as fh:
        fh.write(body)
    print("wrote %s (dead-list head D%02d)" % (MAP, dead_list_head()))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
